import { existsSync, readFileSync, writeFileSync } from "fs";
import { dirname, join } from "path";
import { downloadOverpassData } from "./download.ts";
import { ReverseGeolocator } from "./reverse-geolocation.ts";
import type { CliffPoint, OverpassRequest, RegionCliffs } from "./types.ts";

/**
 * Cliffs are downloaded on the build only (issue #55): there are more than a million of them
 * worldwide, which is too much for a client query, but per region and on demand (the app
 * downloads the cliffs.json of a region at high zoom) it stays reasonable. `out center` without
 * `meta` keeps the raw cache small: the app fetches full elements from the OSM API when editing.
 */
export const WORLD_CLIFFS_QUERY = `
[out:json][timeout:1800];
nwr["natural"="cliff"];
out center;`;

export async function downloadCliffsData(
  outputFilePath: string,
  { force = false, onRetry }: { force?: boolean; onRetry?: (error: string) => void } = {},
): Promise<string> {
  return downloadOverpassData(WORLD_CLIFFS_QUERY, outputFilePath, { force, onRetry, subject: "cliffs data" });
}

function toCliffPoint(el: OverpassRequest["elements"][number]): CliffPoint | undefined {
  // @ts-ignore `center` is added by `out center`
  const coordinates: { lat: number; lon: number } | undefined = el.type === "node" ? el : el.center;
  if (!coordinates) return;
  const tags = el.tags ?? {};
  return {
    id: `${el.type[0]}${el.id}`,
    lon: coordinates.lon,
    lat: coordinates.lat,
    name: tags.name || tags.official_name || undefined,
  };
}

/**
 * Geolocates every cached cliff like the climbing places, and writes a `cliffs.json` file in
 * each region directory that already exists (i.e. holds climbing data): cliffs in regions
 * without any crag are unreachable in the app, so they are dropped.
 */
export async function generateCliffFiles(options: {
  geoIndexFile: string;
  reverseGeocodingDataDirectory: string;
  cliffsDataFile: string;
  outApiDirectory: string;
  maxCacheSize?: number;
}) {
  if (!existsSync(options.cliffsDataFile)) {
    throw new Error(`Missing cliffs data: Please ensure ${options.cliffsDataFile} exists.`);
  }
  const rawData: OverpassRequest = JSON.parse(readFileSync(options.cliffsDataFile, "utf8"));
  const timestamp = rawData.osm3s?.timestamp_osm_base ?? "";

  const geolocator = new ReverseGeolocator(
    options.geoIndexFile,
    options.reverseGeocodingDataDirectory,
    options.maxCacheSize,
  );

  /** Cliffs by region path relative to the API directory (`world/americas/.../laurentides`) */
  const byRegion = new Map<string, CliffPoint[]>();
  let outside = 0;
  for (const el of rawData.elements) {
    const point = toCliffPoint(el);
    if (!point) continue;
    // The center of a long cliff way can fall outside of its region on the borders: acceptable,
    // only the crags displayed next to it matter.
    const location = geolocator.geolocate(point.lon, point.lat);
    if (!location) {
      outside++;
      continue;
    }
    const region = location.join("/");
    let cliffs = byRegion.get(region);
    if (!cliffs) byRegion.set(region, (cliffs = []));
    cliffs.push(point);
  }

  let written = 0;
  for (const [region, cliffs] of byRegion) {
    const target = join(options.outApiDirectory, region, "cliffs.json");
    // Only regions generated by the climbing data pipeline exist
    if (!existsSync(dirname(target))) continue;
    const data: RegionCliffs = { timestamp, cliffs };
    writeFileSync(target, JSON.stringify(data));
    written++;
  }
  console.info(
    `cliffs: ${byRegion.size} regions with cliffs, ${written} files written, ${outside} outside of every region`,
  );
}
