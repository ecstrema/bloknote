import { execSync } from "child_process";
import { cpSync, createReadStream, existsSync, statSync } from "fs";
import { basename, join, normalize, resolve } from "path";
import { fileURLToPath } from "url";
import adapter from "@sveltejs/adapter-static";
import tailwindcss from "@tailwindcss/vite";
import devtoolsJson from "vite-plugin-devtools-json";
import { sveltekit } from "@sveltejs/kit/vite";
import { wuchale } from "wuchale/vite";
import { defineConfig, type Plugin } from "vitest/config";

const BASE = "/bloknote";
const API_PREFIX = `${BASE}/api/world/`;
const WORLD_DIR = resolve(fileURLToPath(import.meta.url), "../../climbing-data-gen/build/world");
const OSM_INDEX_DIR = resolve(WORLD_DIR, "../osm-index");
const OSM_INDEX_PREFIX = `${BASE}/api/osm-index/`;
const HIERARCHY_INDEX_FILE = resolve(
  fileURLToPath(import.meta.url),
  "../../reverse-geocoding-data/output/hierarchy-index.json",
);
const HIERARCHY_INDEX_PATH = `${BASE}/api/hierarchy-index.json`;
const API_FILES = new Set(["data.json", "children.json", "stats.json", "download.json", "data-version.json"]);

function getAppVersion(): string {
  try {
    return execSync("git rev-parse HEAD", { stdio: ["ignore", "pipe", "ignore"] }).toString().trim();
  } catch {
    return "local";
  }
}

/**
 * The static API is generated by climbing-data-gen: it is never a SvelteKit route, so it is not
 * prerendered. The dev server serves it from the generated folder, and the build copies it.
 */
function climbingApi(): Plugin {
  return {
    name: "bloknote-static-api",
    buildStart() {
      if (existsSync(join(WORLD_DIR, "download.json")) && existsSync(join(WORLD_DIR, "data-version.json"))) return;
      execSync("bun run build:climbing-data-gen", { cwd: resolve(WORLD_DIR, "../../../.."), stdio: "inherit" });
    },
    configureServer(server) {
      server.middlewares.use((req, res, next) => {
        const pathname = decodeURIComponent((req.url ?? "").split("?")[0]!);
        if (pathname === HIERARCHY_INDEX_PATH) {
          if (!existsSync(HIERARCHY_INDEX_FILE)) return next();
          res.setHeader("content-type", "application/json");
          createReadStream(HIERARCHY_INDEX_FILE).pipe(res);
          return;
        }
        if (pathname.startsWith(OSM_INDEX_PREFIX)) {
          const indexFile = normalize(join(OSM_INDEX_DIR, pathname.slice(OSM_INDEX_PREFIX.length)));
          if (!indexFile.startsWith(OSM_INDEX_DIR) || !existsSync(indexFile)) return next();
          res.setHeader("content-type", "application/json");
          createReadStream(indexFile).pipe(res);
          return;
        }
        if (!pathname.startsWith(API_PREFIX) || !API_FILES.has(basename(pathname))) return next();

        const file = normalize(join(WORLD_DIR, pathname.slice(API_PREFIX.length)));
        if (!file.startsWith(WORLD_DIR) || !existsSync(file) || !statSync(file).isFile()) return next();

        res.setHeader("content-type", "application/json");
        createReadStream(file).pipe(res);
      });
    },
  };
}

// The fallback lets unknown URLs load the app client-side, which renders the "not found" page
const staticAdapter = adapter({ fallback: "404.html" });

export default defineConfig({
  plugins: [
    climbingApi(),
    tailwindcss(),
    wuchale({ hmrDelayThreshold: 5000 }),
    sveltekit({
      // Consult https://kit.svelte.dev/docs/integrations#preprocessors
      // for more information about preprocessors
      preprocess: [],
      adapter: {
        ...staticAdapter,
        async adapt(builder) {
          await staticAdapter.adapt(builder);
          if (existsSync(HIERARCHY_INDEX_FILE)) {
            cpSync(HIERARCHY_INDEX_FILE, join("build", "api", "hierarchy-index.json"));
          }
          if (existsSync(OSM_INDEX_DIR)) {
            cpSync(OSM_INDEX_DIR, join("build", "api", "osm-index"), { recursive: true });
          }
          if (existsSync(WORLD_DIR)) {
            cpSync(WORLD_DIR, join("build", "api", "world"), {
              recursive: true,
              filter: (source) => statSync(source).isDirectory() || API_FILES.has(basename(source)),
            });
          }
        },
      },
      paths: { base: BASE },
      prerender: { concurrency: 8, handleUnseenRoutes: "warn", handleInvalidUrl: "warn" },
      version: {
        pollInterval: 15 * 60 * 1000 /* 15 minutes */,
        name: getAppVersion(),
      },
    }),
    devtoolsJson(),
  ],
  test: { include: ["src/**/*.{test,spec}.{js,ts}"] },
  server: {
    host: "127.0.0.1",
    watch: {
      ignored: ["**/src/locales/*.po"],
    },
  },
  optimizeDeps: {
    // MapLibre loads its worker from next to its own module: pre-bundling would move the module
    // to .vite/deps without the worker
    exclude: ["maplibre-gl", "@sqlite.org/sqlite-wasm"],
  },
  worker: { format: "es" },
});
